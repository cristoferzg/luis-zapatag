// Clasificación de perfiles por Norma / Acabado Industrial (LAC, Galvanizados, LAF/LAB, ASTM)
export function getNormaAcabadoTechos(p: PerfilTubularItem): 'LAC' | 'LAF' | 'GALVANIZADO' | 'ASTM' {
  if (p.normaAcabado) return p.normaAcabado;
  const n = (p.nombre + ' ' + (p.codigoComercial || '') + ' ' + p.id).toLowerCase();
  if (n.includes('galv') || n.includes('zinc')) return 'GALVANIZADO';
  if (n.includes('laf') || n.includes('lab') || (p.espesorMm <= 1.2 && p.categoria.includes('tubo') && !n.includes('lac'))) return 'LAF';
  if (p.categoria === 'angulo_estructural' || p.categoria === 'platina' || p.categoria === 'perfil_h_ipe' || p.categoria === 'perfil_c' || p.categoria === 'perfil_z') return 'ASTM';
  return 'LAC';
}

